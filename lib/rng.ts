/** Small deterministic PRNG helpers so a run can be replayed from a seed. */

export type Rng = () => number;

/** mulberry32 - fast, good enough distribution, 32-bit state. */
export function mulberry32(seed: number): Rng {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function hashSeed(text: string): number {
  let h = 2166136261;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** Human friendly 6 character seed. */
export function randomSeed(): string {
  let out = '';
  for (let i = 0; i < 6; i++) {
    out += Math.floor(Math.random() * 36).toString(36);
  }
  return out.toUpperCase();
}

/** Fisher-Yates using the supplied rng, returns a new array. */
export function shuffle<T>(items: readonly T[], rng: Rng): T[] {
  const out = items.slice();
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
